"""Проверка каталога на запрещённые темы: экстремизм, терроризм, ЛГБТ и т.д.

Сканирует названия и описания книг в продаже, ищет ключевые слова. Возвращает
список найденных книг с причиной (какая категория). Используется для ручной
модерации перед снятием — автоматического снятия нет (слишком опасно).

ОГРАНИЧЕНИЯ:
- Поиск по ключевым словам даёт ложные срабатывания (например, «героин» находил
  «героини книги» до исправления регулярки).
- Не проверяет авторов-иноагентов по реестру Минюста РФ — такой реестр нужно
  поддерживать вручную (список ФИО) или подключать внешний API.
- Не проверяет книги из федерального списка экстремистских материалов Минюста
  (https://minjust.gov.ru/ru/activity/directions/998/) — этот список содержит
  тысячи позиций и требует точного сопоставления названий.

Чтобы добавить проверку по спискам:
1. Создай файл app/data/foreign_agents.txt (ФИО иноагентов, по одному на строку)
2. Создай файл app/data/banned_books.txt (названия запрещённых книг)
3. Доработай check_catalog_for_forbidden(): после проверки по паттернам добавь
   сверку book.author с foreign_agents.txt и book.title с banned_books.txt.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import Book, BookStatus


@dataclass
class ForbiddenMatch:
    """Одна найденная книга с проблемной темой."""

    book_id: int
    sku: str
    title: str
    author: str | None
    category: str  # «Экстремизм», «ЛГБТ» и т.д.
    matched_word: str  # какое именно слово нашлось


# Словари запрещённых тем. Регистронезависимый поиск по целым словам (граница \b).
# Ищем в названии, авторе и описании. Слова подобраны так, чтобы минимизировать
# ложные срабатывания (исключения оговорены комментариями).
#
# ВАЖНО: список не заменяет официальные реестры Минюста РФ:
#   - Федеральный список экстремистских материалов: minjust.gov.ru/ru/activity/directions/998/
#   - Список организаций, запрещённых как террористические/экстремистские
#   - Реестр иноагентов
# Для точной сверки по этим реестрам см. комментарий в начале файла.
PATTERNS = {
    "Экстремизм": [
        r"\bэкстремизм",
        r"\bэкстремист",
        r"\bрадикал",
        r"\bфашизм",
        r"\bнацизм",
        r"\bнаци\b",
        r"\bваххабизм",
        r"\bваххабит",
        r"\bсалафизм",
        r"\bсалафит",
    ],
    "Терроризм": [
        r"\bтеррор",
        r"\bджихад",
        r"\bтеракт",
        r"\bбоевик",
    ],
    "Иноагенты": [
        r"\bиноагент",
        r"\bиностранный\s+агент",
    ],
    "ЛГБТ": [
        r"\bлгбт",
        r"\bгей[-\s]парад",   # конкретный маркер — без него «гей» ловит биографии и пр.
        r"\bгей\b",
        r"\bлесбиянк",
        r"\bтрансгенд",
        r"\bквир",
        r"\bгомосексуал",
    ],
    "Запрещённые организации": [
        # Террористические
        r"\bигил",
        r"\bисис",
        r"\bаль[-\s]каид",
        r"\bталибан",
        r"\bхизб[-\s]ут[-\s]тахрир",
        r"\bбратья[-\s]мусульмане",
        r"\bжзл\b",               # убрать если ложные срабатывания на серию ЖЗЛ
        # Экстремистские
        r"\bсвидетел[ьи]\s+иегов",  # «Свидетели Иеговы»
        r"\bнурсист",               # последователи Нурси (запрещено в РФ)
        r"\bауе\b",                 # криминальная субкультура
        r"\bрнс\b",                 # Русское национальное единство
        r"\bпатриот[иы]\b",         # «Патриоты России» — снять если много ложных срабатываний
    ],
    "Суицид": [
        r"\bсуицид",
        # «самоубийств» — широкое слово, ловит и художественную литературу.
        # Оставляем: лучше ложное срабатывание, чем пропустить реальный риск.
        r"\bсамоубийств",
    ],
    "Педофилия": [
        r"\bпедофил",
        r"\bдетская\s+порнограф",
    ],
    "Наркотики": [
        r"\bнаркотик",
        r"\bкокаин\b",
        # «героин» без \b на конце ловил «героини книги» — теперь только точная
        # форма слова и падежи существительного, но не «героиня/героини».
        r"\bгероин(?:а|у|ом|е)?\b",
        r"\bметамфетамин",
        r"\bпсихотроп",
        r"\bнаркоман",
        r"\bмарихуан",
        r"\bканнабис",
        r"\bвейп",             # под вопросом: вейп — легальный товар, но встречается в ограничениях
    ],
    "Грубые слова": [
        r"\bотребье",
        r"\bподонок",
        r"\bсволоч",
        r"\bублюдок",
    ],
}


def check_catalog_for_forbidden(db: Session) -> list[ForbiddenMatch]:
    """Просканировать каталог в продаже, вернуть список книг с проблемными темами.

    Ищет только в книгах со статусом IN_STOCK — снятое и проданное уже не актуально.
    Сканирует title, author, description. Возвращает список совпадений с указанием
    категории и конкретного слова.
    """
    books = db.scalars(
        select(Book).where(Book.status == BookStatus.IN_STOCK)
    ).all()

    results: list[ForbiddenMatch] = []
    for book in books:
        # Собираем текст для поиска: название + автор + описание (если есть)
        text_parts = [book.title or ""]
        if book.author:
            text_parts.append(book.author)
        if book.description:
            text_parts.append(book.description)
        full_text = " ".join(text_parts)

        # Проверяем каждую категорию
        for category, patterns in PATTERNS.items():
            for pattern in patterns:
                match = re.search(pattern, full_text, re.IGNORECASE)
                if match:
                    results.append(
                        ForbiddenMatch(
                            book_id=book.id,
                            sku=book.sku,
                            title=book.title,
                            author=book.author,
                            category=category,
                            matched_word=match.group(0),
                        )
                    )
                    # Нашли одно совпадение в этой категории — переходим к следующей
                    # (не дублируем книгу, если в ней 2 слова из одной категории)
                    break
    return results
